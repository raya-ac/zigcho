    fn param(buffers: *[32][64]u8, cursor: *usize, value: anytype) ![]u8 {
        if (cursor.* == buffers.len) return error.ParameterBufferExhausted;
        const index = cursor.*;
        cursor.* += 1;
        return std.fmt.bufPrint(&buffers[index], "{d}", .{value});
    }

