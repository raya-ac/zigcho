        var result = try postgres.queryParams(self.allocator, lease.conn, "UPDATE zigcho.users SET password_hash=$1,password_salt=$2 WHERE id=$3 AND password_hash=$4", &.{ hash_bytea, salt_bytea, id, previous_bytea });
