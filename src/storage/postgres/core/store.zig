pub fn bindObjectStorage(self: anytype, object_store: r2.Storage) void {
    self.object_store = object_store;
}

pub fn close(self: anytype) void {
    self.pool.deinit();
}

pub fn rotateStableScoreSession(self: anytype, user_id: i32, token: []const u8, binding: stable_client.Binding, now: i64, grace_seconds: i64) !void {
    return postgres_stable_sessions.rotate(self.allocator, &self.pool, user_id, token, binding, now, grace_seconds);
}

pub fn consumeStableScoreGrace(self: anytype, token: []const u8, user_id: i32, binding: stable_client.Binding, submission_checksum: []const u8, now: i64) !StableScoreGraceResult {
    return postgres_stable_sessions.consume(self.allocator, &self.pool, token, user_id, binding, submission_checksum, now);
}

pub fn revokeStableScoreSessionsForUser(self: anytype, user_id: i32) !usize {
    return postgres_stable_sessions.revoke(self.allocator, &self.pool, user_id, std.Io.Clock.real.now(self.io).toSeconds());
}

pub fn refreshExternalOnly(self: anytype, conn: *postgres.c.PGconn) !void {
    var result = try postgres.query(conn, "SELECT count(*) FROM information_schema.columns WHERE table_schema='zigcho' AND is_nullable='YES' AND ((table_name='beatmap_archives' AND column_name='osz_file') OR (table_name='beatmap_media' AND column_name='data'))");
    defer result.deinit();
    self.external_only = try result.int(i32, 0, 0) == 2;
}

